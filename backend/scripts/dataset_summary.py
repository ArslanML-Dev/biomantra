"""Write docs/report_pack/data/dataset_summary.md from the real data files (report pack).

Usage (from backend/):
    python scripts/dataset_summary.py
"""
import sys
from pathlib import Path

import pandas as pd

BACKEND_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BACKEND_DIR))
from scripts.make_dataset import MAIN_COLS, fill_short_gaps, load_csv, pct_missing  # noqa: E402
from scripts.train_forecast import shared_rows, time_split  # noqa: E402

OUT = BACKEND_DIR.parent / "docs" / "report_pack" / "data" / "dataset_summary.md"


def merged_before_filling() -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """Rebuild the merged hourly table exactly like make_dataset.py, before gap filling."""
    air = load_csv("air_raw.csv").rename(columns={"pm2_5": "pm25"})
    weather = load_csv("weather_raw.csv")
    df = air.join(weather, how="outer")
    start, end = max(air.index.min(), weather.index.min()), min(air.index.max(), weather.index.max())
    return df.reindex(pd.date_range(start, end, freq="h", tz="UTC", name="time")), air, weather


def main() -> None:
    """Compute the summary numbers and write the markdown file."""
    raw, air, weather = merged_before_filling()
    filled = raw.copy()
    for col in filled.columns:
        filled[col] = fill_short_gaps(filled[col])
    saved = pd.read_parquet(BACKEND_DIR / "data" / "hourly.parquet")
    df = saved.asfreq("h")
    rows = shared_rows(df)
    X = pd.DataFrame(index=rows)
    split = time_split(X, pd.Series(0, index=rows))
    before, after = pct_missing(raw), pct_missing(filled)
    describe = saved[MAIN_COLS].describe().round(2)

    lines = [
        "# Dataset summary",
        "",
        "Generated by `backend/scripts/dataset_summary.py` from the real files in `backend/data/`.",
        "",
        "## Sources",
        "- **PM2.5:** Open-Meteo Air Quality API (CAMS modelled/reanalysis data), hourly, UTC. "
        f"`air_raw.csv`: {len(air):,} rows, {air.index.min()} → {air.index.max()}.",
        "- **Weather:** Open-Meteo historical archive (temperature 2 m, relative humidity 2 m, wind speed and "
        f"direction 10 m, precipitation). `weather_raw.csv`: {len(weather):,} rows, {weather.index.min()} → {weather.index.max()}.",
        f"- Location: the campus coordinates in `backend/.env` (LAT/LON). Open-Meteo PM2.5 history starts on 2022-08-04.",
        "",
        "## Merged hourly table (`hourly.parquet`)",
        f"- Rows: **{len(saved):,}** hourly rows, {saved.index.min()} → {saved.index.max()} (UTC).",
        "- Join on UTC hour, reindex to every hour of the overlap, linear interpolation of gaps ≤ 3 h only.",
        "",
        "| Column | % missing before filling | % missing after filling |",
        "|---|---|---|",
        *[f"| {c} | {before[c]} | {after[c]} |" for c in MAIN_COLS],
        "",
        "## Descriptive statistics (`df.describe()`)",
        "",
        "Units: pm25 µg/m³, temp °C, rh %, wind_speed km/h.",
        "",
        "| Statistic | " + " | ".join(MAIN_COLS) + " |",
        "|---|" + "---|" * len(MAIN_COLS),
        *[f"| {stat} | " + " | ".join(str(describe.loc[stat, c]) for c in MAIN_COLS) + " |" for stat in describe.index],
        "",
        "## Train / validation / test split (time order, never shuffled)",
        "",
        f"Rows usable by every model configuration (all lags, rolling windows, next-24 h target and weather present): **{len(rows):,}**.",
        "",
        "| Part | Share | Rows | From (UTC) | To (UTC) |",
        "|---|---|---|---|---|",
        *[f"| {name} | {share} | {len(part[0]):,} | {part[0].index.min()} | {part[0].index.max()} |"
          for (name, part), share in zip(split.items(), ["70 %", "15 %", "15 %"])],
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"saved {OUT}")


if __name__ == "__main__":
    main()
